# Descripción:
# La función len() devuelve la cantidad de elementos que tiene un objeto.
# Se puede utilizar con listas, cadenas de texto, tuplas y otros objetos.
# Es muy útil para saber el tamaño de una colección o la cantidad de
# caracteres que contiene un texto.

ciudades = ["Bogotá", "Medellín", "Cali", "Cartagena"]
print(len(ciudades))
