# Descripción:
# La función dict() se utiliza para crear un diccionario en Python.
# Un diccionario almacena información en pares de clave y valor,
# permitiendo organizar los datos de una manera clara y acceder
# rápidamente a cada elemento utilizando su clave.

datos = [("Nombre", "Carlos"), ("Edad", 21)]
print(dict(datos))
